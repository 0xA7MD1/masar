/** Same line all day, a new one tomorrow. */
export function dailyLine(today: string): string {
  const dayNumber = Math.floor(parseISODate(today).getTime() / 86_400_000);
  return LINES[dayNumber % LINES.length];
}

export function greeting(hour: number): string {
  return hour >= 4 && hour < 12 ? "صباح الخير" : "مساء الخير";
}
